import math


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    return a / b


def power(a, b):
    return a**b


def square_root(a):
    return math.sqrt(a)


def absolute(a):
    return abs(a)


def is_even(a):
    return a % 2 == 0


def is_odd(a):
    return a % 2 != 0
